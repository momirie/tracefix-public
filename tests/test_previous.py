def _edit(folder: Path, change: object) -> None:
    data = json.loads((folder / "receipt.json").read_text(encoding="utf-8"))
    change(data)  # type: ignore[operator]
    (folder / "receipt.json").write_text(json.dumps(data), encoding="utf-8")


def _set(path: list[object], value: object) -> object:
    def change(data: dict[str, object]) -> None:
        node: object = data
        for key in path[:-1]:
            node = node[key]  # type: ignore[index]
        node[path[-1]] = value  # type: ignore[index]

    return change


@pytest.mark.parametrize(
    ("change", "says"),
    [
        (_set(["findings", 0, "file"], "findings/../../x.py"), "names the file"),
        (_set(["findings", 0, "file"], None), "names the file"),
        (_set(["findings", 0, "number"], 0), "not distinct positive numbers"),
        (_set(["head", "sha"], "not a sha"), "not a commit id"),
        (_set(["created_at"], "yesterday"), "not a date"),
        (_set(["level"], "L9"), "not a valid receipt"),
        (_set(["schema_version"], 2), "not a valid receipt"),
        (_set(["extra"], 1), "not a valid receipt"),
        (_set(["findings", 0, "number"], "1"), "not a valid receipt"),  # strict: no coercion
        (lambda d: d["findings"].extend([d["findings"][0]] * 5), "lists 6 findings"),
    ],
)
def test_a_forged_receipt_is_not_used(tmp_path: Path, ws_dummy: Workspace, change: object,
                                      says: str) -> None:  # fmt: skip
    folder = old_folder(tmp_path / "old", ws_dummy, [EMPTY])
    _edit(folder, change)
    loaded = load(folder)
    assert says in loaded.problem and loaded.findings == ()
    assert loaded.problem.startswith("the last receipt can't be used: ")


