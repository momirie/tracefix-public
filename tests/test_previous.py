# --- earlier findings stay open until shown fixed (developer, 14 Oct 2026; verifier M9 B2) -------


def later_folder(folder: Path, ws: Workspace, previous: Previous,
                 result: PreviousResult | None) -> Path:  # fmt: skip
    """A later run's `--out`: its replay of `previous` (None: it never ran), nothing new found."""
    record = l4_run()
    if result is not None:
        replayed = StageRecord(PREVIOUS, result.status.value, result.reason, result=result)
        record = dataclasses.replace(record, stages=(*record.stages, replayed))
    record = dataclasses.replace(record, still_open=still_open(previous, result))
    write_out(folder, Verified(record, build(record, ws)))
    return folder


def test_a_finding_still_failing_is_replayed_on_every_later_push(
    tmp_path: Path, ws_dummy: Workspace
) -> None:
    """A: finding 1. B replays it (still fails) and finds nothing new. C, on the same code, must
    replay it again: one more push may not forget it."""
    a = load(old_folder(tmp_path / "a", ws_dummy, [EMPTY, NUMBER]))
    on_b = replay_on(tmp_path / "b", PARTIAL, a)
    assert results(on_b) == [(1, Replay.STILL_FAILS), (2, Replay.FIXED)]
    b = later_folder(tmp_path / "b-out", ws_dummy, a, on_b)
    receipt = json.loads((b / "receipt.json").read_text(encoding="utf-8"))
    assert receipt["findings"] == []
    assert [(f["number"], f["file"]) for f in receipt["previous"]["still_open"]] == [
        (1, "findings/previous_1.py")
    ]
    assert (b / "findings" / "previous_1.py").read_text(encoding="utf-8") == EMPTY
    loaded = load(b)
    assert [(f.number, f.carried, f.file) for f in loaded.findings] == [
        (1, True, "findings/previous_1.py")
    ]
    on_c = replay_on(tmp_path / "c", PARTIAL, loaded)
    assert [(f.number, f.carried, f.result) for f in on_c.findings] == [
        (1, True, Replay.STILL_FAILS)
    ]
    assert on_c.runs[0][0] == "earlier finding 1 (still open in the last receipt), attempt 1"
    gate = previous_gate(run(StageRecord(PREVIOUS, "replayed", "", result=on_c)))
    assert gate.reasons == (
        "earlier finding 1 (still open in the last receipt) (parse_port(raw='')) still fails on "
        "this commit",
    )
    assert still_open(loaded, on_c).findings == loaded.findings
    fixed = replay_on(tmp_path / "d", FIXED, loaded)
    assert results(fixed) == [(1, Replay.FIXED)] and still_open(loaded, fixed).findings == ()


def test_findings_not_replayed_stay_open(tmp_path: Path, ws_dummy: Workspace) -> None:
    """The run stopped before the replay, or the replay did not finish: none was shown fixed."""
    a = load(old_folder(tmp_path / "a", ws_dummy, [EMPTY, NUMBER]))
    invalid = PreviousResult(PreviousStatus.INVALID, "tampering", a.head_sha, a.level, a.created_at)
    assert still_open(a, None).findings == a.findings
    assert still_open(a, invalid).findings == a.findings
    b = later_folder(tmp_path / "b", ws_dummy, a, None)
    assert [(f.number, f.call, f.code) for f in load(b).findings] == [
        (1, "parse_port(raw='')", EMPTY),
        (2, "parse_port(raw='')", NUMBER),
    ]
    md = (b / "receipt.md").read_text(encoding="utf-8")
    assert ("**Since the last receipt:** not replayed (the run stopped before the replay); "
            "2 earlier finding(s) still open") in md  # fmt: skip


def replayed_as(previous: Previous, result: Replay) -> PreviousResult:
    """A finished replay in which every old finding ended `result` (no runs)."""
    found = tuple(Replayed(f.number, f.call, f.file, result, "x", carried=f.carried)
                  for f in previous.findings)  # fmt: skip
    return PreviousResult(PreviousStatus.REPLAYED, "", previous.head_sha, previous.level,
                          previous.created_at, found)  # fmt: skip


def pushed(folder: Path, ws: Workspace, previous: Previous, result: PreviousResult,
           own: tuple[str, ...]) -> Path:  # fmt: skip
    """A later run's `--out` whose own Break My Fix found the files `own`."""
    found = tuple(finding(i, function="port.parse_port", input=(("raw", "''"),), repro_code=code,
                          expect=IN_FILE) for i, code in enumerate(own, start=1))  # fmt: skip
    record = l4_run(break_my_fix=attack(status=AttackStatus.FOUND, findings=found))
    replayed = StageRecord(PREVIOUS, result.status.value, result.reason, result=result)
    record = dataclasses.replace(record, stages=(*record.stages, replayed),
                                 still_open=still_open(previous, result, own))  # fmt: skip
    write_out(folder, Verified(record, build(record, ws)))
    return folder


def test_a_counterexample_found_again_is_carried_once(tmp_path: Path, ws_dummy: Workspace) -> None:
    """Each push re-finds the same counterexample as its own finding 1: the open list must not
    grow until the PR can never reach L4 again (verifier M9 round 2, B2)."""
    previous = load(old_folder(tmp_path / "a", ws_dummy, [EMPTY]))
    for push in range(1, 8):
        again = finding_code(push + 1, "assert parse_port('') == 8080")  # numbered anew
        folder = pushed(tmp_path / f"p{push}", ws_dummy, previous,
                        replayed_as(previous, Replay.STILL_FAILS), (again,))  # fmt: skip
        previous = load(folder)
        assert previous.problem == ""
        assert [(f.number, f.carried) for f in previous.findings] == [(1, False)], push
    other = finding_code(5, "assert parse_port('7') == 7")  # a different check stays carried
    duplicate = finding_code(9, "assert parse_port('') == 8080")
    assert prev.same_check(duplicate) == prev.same_check(EMPTY) != prev.same_check(other)
    two = Previous("b" * 40, "L2", "2026-10-14T09:00:00+00:00", (
        OldFinding(1, "f()", "findings/finding_1.py", EMPTY, None),
        OldFinding(2, "f()", "findings/finding_2.py", duplicate, None),
        OldFinding(3, "f()", "findings/finding_3.py", other, None)))  # fmt: skip
    assert [f.number for f in still_open(two, None).findings] == [1, 3]


