LEVEL = sandbox_level()
PYPROJECT = '[tool.pytest.ini_options]\npythonpath = ["src"]\n'
BUGGY = "def parse_port(raw):\n    return int(raw)\n"
FIXED = "def parse_port(raw):\n    return int(raw) if raw else 8080\n"
