def test_each_old_finding_gets_its_result(tmp_path: Path, ws_dummy: Workspace) -> None:
    folder = old_folder(tmp_path / "old", ws_dummy, [EMPTY, NUMBER, RENAMED, WORD])
    result = replay_on(tmp_path, PARTIAL, load(folder))
    assert result.status is PreviousStatus.REPLAYED, result.reason
    assert results(result) == [(1, Replay.STILL_FAILS), (2, Replay.FIXED),
                               (3, Replay.CANNOT_RUN), (4, Replay.FAILS_DIFFERENTLY)]  # fmt: skip
    still, fixed, cannot, other = result.findings
    assert "assert 0 == 8080" in still.detail and "3 of 3 attempts" in still.detail
    assert fixed.detail == f"passed {PASSES} times in a row"
    assert "read_port" in cannot.detail
    assert other.detail.startswith("it failed with ValueError, not AssertionError (ValueError: ")
    # Three runs each, except the one that can't run (it stops at the first error).
    labels = [label for label, _ in result.runs]
    assert len(labels) == 3 + 3 + 1 + 3
    assert labels[0] == "finding 1 of the last receipt, attempt 1"
    assert (result.head_sha, result.level) == ("b" * 40, "COUNTEREXAMPLE")
    assert result.reason == ("4 earlier findings replayed: 1 fixed, 1 still fails, "
                             "1 still fails, in a different way, 1 can't run")  # fmt: skip
    assert result.isolation == LEVEL


def test_a_complete_fix_fixes_every_old_finding(tmp_path: Path, ws_dummy: Workspace) -> None:
    folder = old_folder(tmp_path / "old", ws_dummy, [EMPTY])
    result = replay_on(tmp_path, FIXED, load(folder))
    assert results(result) == [(1, Replay.FIXED)], result.reason
    assert len(result.runs) == PASSES  # never fixed after one pass
    gate = previous_gate(run(StageRecord(PREVIOUS, "replayed", "", result=result)))
    assert gate.allowed


