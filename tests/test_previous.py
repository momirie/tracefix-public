TESTS = "from port import parse_port\n\n\ndef test_port():\n    assert parse_port('80') == 80\n"
IN_FILE = Expectation(frozenset({"AssertionError"}), True)


def finding_code(number: int, body: str, imported: str = "parse_port") -> str:
    return (f"# Break My Fix finding {number}, generated by Tracefix\n"
            f"from port import {imported}\n\n\n"
            f"def test_break_my_fix_{number}() -> None:\n    {body}\n")  # fmt: skip


# What each finding file checks, and what PARTIAL does with it.
EMPTY = finding_code(1, "assert parse_port('') == 8080")  # PARTIAL gives 0: still fails
NUMBER = finding_code(2, "assert parse_port('80') == 80")  # passes: fixed
RENAMED = finding_code(3, "assert read_port('') == 8080", "read_port")  # import error
WORD = finding_code(4, "assert parse_port('x') == 0")  # ValueError inside port.py


@pytest.fixture
def ws_dummy(tmp_path: Path) -> Workspace:
    """Only the folders matter: the receipt masks them."""
    repo = tmp_path / "dummy"
    repo.mkdir()
    workspace = Workspace(repo, "main", "fix")
    workspace.root = tmp_path / "work"
    return workspace


def old_folder(folder: Path, ws: Workspace, codes: list[str],
               expect: Expectation | None = IN_FILE) -> Path:  # fmt: skip
    """An earlier `--out` folder: receipt.json, receipt.md and findings/finding_<n>.py."""
    found = tuple(
        finding(i, function="port.parse_port", input=(("raw", "''"),), repro_code=code,
                expect=expect)
        for i, code in enumerate(codes, start=1)
    )  # fmt: skip
    record = l4_run(break_my_fix=attack(status=AttackStatus.FOUND, findings=found))
    write_out(folder, Verified(record, build(record, ws)))
    return folder


def replay_on(tmp_path: Path, head: str, previous: Previous,
              also: dict[str, str | None] | None = None) -> PreviousResult:  # fmt: skip
    files = {"pyproject.toml": PYPROJECT, "src/port.py": BUGGY, "tests/test_port.py": TESTS}
    repo = make_repo(tmp_path / "repo", [files, {"src/port.py": head, **(also or {})}])
    with Workspace(repo, "c0", "c1") as ws:
        return replay(ws, previous)


def results(result: PreviousResult) -> list[tuple[int, Replay]]:
    return [(f.number, f.result) for f in result.findings]


