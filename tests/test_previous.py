def test_the_actions_unusable_marker_makes_the_replay_inconclusive(tmp_path: Path) -> None:
    (tmp_path / UNUSABLE).write_text("the zip can't be read\n(BadZipFile)", encoding="utf-8")
    assert (
        load(tmp_path).problem
        == "the last receipt can't be used: the zip can't be read (BadZipFile)"
    )
    (tmp_path / UNUSABLE).write_bytes(b"\xff" * 10)
    assert load(tmp_path).problem == "the last receipt can't be used: no reason given"
