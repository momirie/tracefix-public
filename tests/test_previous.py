def test_tampering_makes_the_stage_invalid(tmp_path: Path, ws_dummy: Workspace) -> None:
    target = tmp_path / "repo" / "src" / "port.py"  # the user's own repo, outside the copy
    hostile = finding_code(1, f"open({target.as_posix()!r}, 'a').write('# x')")
    folder = old_folder(tmp_path / "old", ws_dummy, [hostile])
    result = replay_on(tmp_path, FIXED, load(folder))
