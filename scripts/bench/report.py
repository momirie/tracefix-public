def judged_runs(
    cases: Sequence[Case], lines: Sequence[RunLine],
    receipts: Mapping[tuple[str, str, int], Receipt | None],
) -> tuple[list[Run], list[Run], list[Run]]:  # fmt: skip
    """(runs, first, aside): each run's last line of the slice's cases; the first repeats with a
    receipt, which the headline sections read; and those of them set aside because they rest on
    tests the PR updated (`rests_on_updated_tests`). Also read by scripts/site_data.py."""
    ids = {c.task.instance_id for c in cases}
    updated = {c.task.instance_id: updated_tests(c.task) for c in cases}
    runs = [Run(line, receipts.get(key)) for key, line in sorted(latest(lines).items())]
    runs = [r for r in runs if r.line.instance_id in ids]
    first = [r for r in runs if r.line.repeat == 1 and r.receipt is not None]
    gold_first = {r.line.instance_id: r.receipt for r in first if r.line.kind == "gold"}
    aside = [
        r
        for r in first
        if rests_on_updated_tests(
            r, updated[r.line.instance_id], gold_first.get(r.line.instance_id)
        )
    ]
    return runs, first, aside


def summarise(
    cases: Sequence[Case], prepared: Mapping[str, Prepared], lines: Sequence[RunLine],
    receipts: Mapping[tuple[str, str, int], Receipt | None], labels: Labels, reserve: float,
) -> Json:  # fmt: skip
    """summary.json. Headline sections read each task's first repeat; `stability` reads all.
    The gold, partial and separation sections leave out runs that rest on tests the PR updated
    (`rests_on_updated_tests`); the stage sections still read them."""
    split = {c.task.instance_id: c.split for c in cases}
    kinds = kinds_of(cases)
    runs, first, aside = judged_runs(cases, lines, receipts)
    judged = [r for r in first if r not in aside]
    gold_runs = [r for r in first if r.line.kind == "gold"]
    judged_gold = [r for r in judged if r.line.kind == "gold"]
    judged_partial = [r for r in judged if r.line.kind == "partial"]
    by_key = {label.key: label for label in labels.labels if label.label is not None}
    of_kind = {kind: [r for r in first if r.line.kind == kind] for kind in kinds}

    def per_kind(section: Callable[[Sequence[Run]], Json]) -> Json:
        return {kind: section(of_kind[kind]) for kind in kinds}

    return {
        "funnel": funnel(cases, prepared, runs),
        "splits": _counts(split[r.line.instance_id] for r in gold_runs),
        "set_aside": set_aside(first, aside, kinds),
        "gold": gold(judged_gold, by_key),
        "partial": partial(judged_partial, by_key),
        "separation": separation(judged_gold, judged_partial),
        **(agents(judged, judged_gold, prepared, split, by_key) if len(kinds) > 2 else {}),
        "reproducer": reproducer(gold_runs),
        "guard": per_kind(guard),
        "break_my_fix": per_kind(break_my_fix),
        "behaviour_diff": per_kind(behaviour_diff),
        "report_only": per_kind(report_only),
        "cost_and_time": cost_and_time(first, lines, reserve),
        "stability": stability(runs),
        "findings": findings(runs, by_key),
    }


def agents(
    judged: Sequence[Run], judged_gold: Sequence[Run], prepared: Mapping[str, Prepared],
    split: Mapping[str, str], labels: Mapping[Key, FindingLabel],
) -> Json:  # fmt: skip
    """Slice 2's sections: the agents' patches, correct fixes together, gold against a wrong
    agent's patch, and the headline rates by split and by the project's Python."""
    wrong = [r for r in judged if r.line.kind == "agent_wrong"]
    right = [r for r in judged if r.line.kind == "agent_ok"]

    def python(run: Run) -> str | None:
        found = prepared.get(run.line.instance_id)
        return None if found is None else python_group(found.python)

    return {
        "agent_wrong": partial(wrong, labels),
        "agent_ok": agent_ok(right, labels),
        "correct_fixes": gold([r for r in judged if r.line.kind in CORRECT], labels),
        "separation_agent_wrong": separation(judged_gold, wrong),
        "by_split": by_group(
            judged, lambda r: split[r.line.instance_id], ("dev", "held_out"), labels
        ),
        "by_python": by_group(judged, python, PYTHONS, labels),
    }


def _first_reason(reasons: Sequence[str]) -> str:
    more = f" (and {len(reasons) - 1} more)" if len(reasons) > 1 else ""
    return (reasons[0] if reasons else "") + more


def _strings_in(code: str) -> set[str]:
    """Every string constant of a piece of code; none if it doesn't parse."""
    try:
        tree = ast.parse(code, mode="eval")
    except (SyntaxError, ValueError, RecursionError):
        return set()
    return {
        node.value
        for node in ast.walk(tree)
        if isinstance(node, ast.Constant) and isinstance(node.value, str)
    }


def uses_tricky_string(given: Mapping[str, str]) -> bool:
    """Whether a finding's input (parameter -> literal) holds a whole tricky string: alone, in a
    container or among a made-up object's arguments (`self` is the literal of its code). By value,
    not by where it came from, so a model's example "Ab" counts too, in either arm (M11 S6)."""
    found: set[str] = set()
    for param, literal in given.items():
        strings = _strings_in(literal)
        found |= strings
        if param == RECEIVER:
            for code in strings:
                found |= _strings_in(code)
    return not found.isdisjoint(TRICKY_STRINGS)


def findings(
    runs: Sequence[Run], labels: Mapping[tuple[str, str, int], FindingLabel]
) -> list[Json]:
    """Every finding, with its input, outcome, replay on gold and label, for review; a gold
    COUNTEREXAMPLE's causes no finding carries are listed first as `RUN_ITSELF`, its outcome
    those causes (or, with no finding at all, the level's reasons)."""
    out = []
    for r in runs:
        if r.receipt is None:
            continue
        if RUN_ITSELF in _numbers(r):
            label = label_for(r, labels, RUN_ITSELF)
            causes = other_causes(r.receipt) or r.receipt.level_reasons
            out.append({
                "instance_id": r.line.instance_id, "run": r.line.tag, "finding": RUN_ITSELF,
                "call": "(the run's level, not a finding)",
                "outcome": _first_reason(causes), "expected": None,
                "replay_on_gold": None,
                "label": label.label if label else None, "by": label.by if label else None,
            })  # fmt: skip
        replayed = replay_results(r.line)
        for f in r.receipt.findings:
            label = label_for(r, labels, f.number)
            out.append({
                "instance_id": r.line.instance_id, "run": r.line.tag, "finding": f.number,
                "call": f.call, "outcome": f.outcome, "expected": f.expected,
                "replay_on_gold": _on_gold(r, replayed.get(f.number)),
                "label": label.label if label else None, "by": label.by if label else None,
            })  # fmt: skip
    return out


def _on_gold(run: Run, result: Replay | None) -> str | None:
    """A finding's replay on gold; on a correct agent's patch, `fixed` there is DIFFERS."""
    if result is None:
        return None
    return DIFFERS if run.line.kind == "agent_ok" and result is Replay.FIXED else result.value


# --- M11: why a leftover was missed, and two result sets compared ------------------------------

WRONG = ("partial", "agent_wrong")  # incorrect by our hidden runs: the leftover should be found
# Why an incorrect fix's leftover was not found, in fixed words, from the receipt and the prepare
# record only (`miss_cause`). The leftover is the dropped hunk (partial) or where the agent's
# code differs from gold's (agent_wrong).
NO_EFFECT = "no_effect: nothing attackable left"
NOT_RUN = "Break My Fix did not run"
TARGETS_UNKNOWN = "targets unknown (a receipt from before M11)"
LEFTOVER_UNKNOWN = "leftover's functions unknown (prepared before M11)"
NO_SOURCE = "leftover changes no source code"
OUTSIDE = "leftover outside every function"
NOT_TARGET = "leftover's function not a target"
NO_INPUT = "no input ran"
NOT_ATTACKED = "leftover's function a target, not attacked"
NOT_LEFTOVER = "target attacked, its findings not the leftover"
NO_COUNTEREXAMPLE = "target attacked, no counterexample"
# Misses more evidence or better inputs could reach (M11 S9's gate). The rest are out of their
# reach: nothing attackable left, code outside every function, a function never targeted.
REACHABLE = frozenset({NO_INPUT, NOT_ATTACKED, NOT_LEFTOVER, NO_COUNTEREXAMPLE})


def leftover(run: Run, prepared: Prepared | None) -> tuple[Touched, ...] | None:
    """The run's leftover, as prepare recorded it; None when unknown."""
    if prepared is None:
        return None
    if run.line.kind == "partial":
        variant = next((v for v in prepared.variants
                        if variant_kind(v.index) == run.line.variant), None)  # fmt: skip
        return None if variant is None else variant.functions
    agent = next((a for a in prepared.agents if a.kind == run.line.kind), None)
    return None if agent is None else agent.differs


def _fix_label(run: Run, prepared: Prepared | None) -> Label | None:
    if prepared is None:
        return None
    labels = {variant_kind(v.index): v.label for v in prepared.variants}
    labels |= {a.kind: a.label for a in prepared.agents}
    return labels.get(run.line.variant)


def is_target(target: AttackTargetEntry, touched: Touched) -> bool:
    """Break My Fix attacked this function itself, or a public caller on its behalf (the
    target's `via` names the changed function last: attack_inputs' own words)."""
    name = touched.function
    if name is None:
        return False
    itself = target.function == name or target.function.endswith(f".{name}")
    return (target.path == touched.path and itself) or target.via.endswith(f" {name}")


def miss_cause(run: Run, prepared: Prepared | None) -> str | None:
    """Why an incorrect fix's leftover was not found (one of the fixed words above); None for
    any other run: a correct fix, no receipt, or the leftover found."""
    if run.line.kind not in WRONG or run.receipt is None or _leftover_found(run):
        return None
    if _fix_label(run, prepared) is Label.NO_EFFECT:
        return NO_EFFECT
    entry = stage(run.receipt, "break_my_fix")
    targets = run.receipt.attack_targets
    if entry is None or entry.error is not None or (targets is None and "targets"
                                                     not in entry.evidence):  # fmt: skip
        return NOT_RUN
    if targets is None:
        return TARGETS_UNKNOWN
    touched = leftover(run, prepared)
    if touched is None:
        return LEFTOVER_UNKNOWN
    if not touched:
        return NO_SOURCE
    functions = [t for t in touched if t.function is not None]
    if not functions:
        return OUTSIDE
    hit = [t for t in targets if any(is_target(t, f) for f in functions)]
    if not hit:
        return NOT_TARGET
    if not any(t.inputs_tried for t in targets):
        return NO_INPUT
    if not any(t.attacked and t.inputs_tried for t in hit):
        return NOT_ATTACKED
    return NOT_LEFTOVER if run.receipt.findings else NO_COUNTEREXAMPLE


def misses(runs: Sequence[Run], prepared: Mapping[str, Prepared]) -> dict[str, int]:
    found = (miss_cause(r, prepared.get(r.line.instance_id)) for r in runs)
    return _counts(cause for cause in found if cause is not None)


def paired(a_runs: Sequence[Run], b_runs: Sequence[Run]) -> list[tuple[Run, Run]]:
    """The runs of the same task, kind, variant and repeat in two result sets, both with a
    receipt, in key order."""
    a = {r.line.key: r for r in a_runs if r.receipt is not None}
    return [
        (a[r.line.key], r)
        for r in sorted(b_runs, key=lambda r: r.line.key)
        if r.receipt is not None
        and r.line.key in a
        and a[r.line.key].line.variant == r.line.variant
    ]


def sign_test(wins: int, losses: int) -> Fraction:
    """One-sided exact sign test: the chance of `wins` or more of the wins + losses discordant
    pairs going B's way if neither arm were better (binomial, one half each; ties left out)."""
    if wins < 0 or losses < 0:
        raise ValueError("wins and losses are counts")
    n = wins + losses
    return Fraction(sum(math.comb(n, k) for k in range(wins, n + 1)), 2**n)


def _p(value: Fraction) -> str:
    return f"{value.numerator}/{value.denominator} ({float(value):.4f})"


def _discordant(pairs: Sequence[tuple[Run, Run]], test: Any) -> Json:
    """The pairs where only B or only A passes `test`, and the sign test of B better."""
    wins = sum(test(b) and not test(a) for a, b in pairs)
    losses = sum(test(a) and not test(b) for a, b in pairs)
    return {"b_only": wins, "a_only": losses, "sign_test_p": _p(sign_test(wins, losses))}


def _level_moves(pairs: Sequence[tuple[Run, Run]]) -> Json:
    """Per kind, how many units B rates above, below or level with A."""
    moves: dict[str, Counter[str]] = {}
    for a, b in pairs:
        step = "up" if _rank(b) > _rank(a) else "down" if _rank(b) < _rank(a) else "same"
        moves.setdefault(a.line.kind, Counter())[step] += 1
    return {kind: {s: found[s] for s in ("up", "down", "same")}
            for kind, found in sorted(moves.items())}  # fmt: skip


def one_mutant_from_flipping(killed: int, valid: int, not_run: int = 0) -> bool:
    """One mutant going the other way would put a judged run on the other side of KILL_PERCENT%
    (NOTES 24). A run Guard stopped early is read as if every mutant left had been killed, the
    case its stop allows for, so the early stop can't make a verdict look firmer than it is."""
    if not_run == 0 and killed * 100 >= valid * KILL_PERCENT:
        return (killed - 1) * 100 < valid * KILL_PERCENT
    return (killed + not_run + 1) * 100 >= (valid + not_run) * KILL_PERCENT


def _flips(run: Run) -> bool:
    found = _evidence(run, "guard")
    return one_mutant_from_flipping(_int(found.get("killed")), _int(found.get("mutants")),
                                    _int(found.get("not_run")))  # fmt: skip


def guard_mutants(runs: Sequence[Run]) -> Json:
    """Runs Guard judged on their model mutants: how many valid ones, and how many verdicts one
    mutant could flip. Gold apart: M11's plan reads both (NOTES 24). A run Guard stopped early
    leaves out of `mutants` the ones it never ran, so its count says little about how many were
    written: M11's "median ≥ 7" reads the `_not_stopped` rows, the others stay beside them."""
    judged = [r for r in runs if _status(r, "guard") in ("guarded", "not_guarded")
              and _int(_evidence(r, "guard").get("mutants")) > 0]  # fmt: skip
    golds = [r for r in judged if r.line.kind == "gold"]

    def counts(of: Sequence[Run]) -> list[float]:
        return [float(_int(_evidence(r, "guard").get("mutants"))) for r in of]

    def not_stopped(of: Sequence[Run]) -> list[Run]:
        return [r for r in of if _int(_evidence(r, "guard").get("not_run")) == 0]

    return {
        "valid_mutants": _stats(counts(judged)),
        "gold_valid_mutants": _stats(counts(golds)),
        "valid_mutants_not_stopped": _stats(counts(not_stopped(judged))),
        "gold_valid_mutants_not_stopped": _stats(counts(not_stopped(golds))),
        "one_mutant_from_flipping": _rate_of(judged, _flips),
        "gold_one_mutant_from_flipping": _rate_of(golds, _flips),
    }


def _no_input(run: Run) -> bool:
    return _reason(run, "break_my_fix") == NO_INPUT_REASON


def blind_counterfactual(runs: Sequence[Run]) -> Json:
    """The blind test (report only) per kind, and what a rule using it would do: of the runs at
    L2 or above, how many it would cap at L1 because the blind test still fails on head. On a
    wrong fix that is a catch; on a correct fix, a loss. No level reads this (M11 S7)."""
    two = rank(EvidenceLevel.L2)
    ran = [r for r in runs if _status(r, BLIND) != "absent"]
    kinds = sorted({r.line.kind for r in ran})
    high = {kind: [r for r in ran if r.line.kind == kind and _rank(r) >= two] for kind in kinds}

    def capped(run: Run) -> bool:
        return _status(run, BLIND) in BLIND_CAPS

    return {
        "statuses": {
            kind: _counts(_status(r, BLIND) for r in ran if r.line.kind == kind) for kind in kinds
        },
        "rule_would_cap_at_l1": {kind: _rate_of(high[kind], capped) for kind in kinds},
    }


def _kinds(runs: Sequence[Run]) -> list[str]:
    return sorted({r.line.kind for r in runs})


def _found(run: Run) -> list[FindingEntry]:
    assert run.receipt is not None
    return run.receipt.findings


def _older(run: Run) -> list[FindingEntry]:
    assert run.receipt is not None
    return run.receipt.pre_existing


def _found_only_through(run: Run, numbers: set[int]) -> bool:
    """Of a run that found its leftover: every finding that found it is one of these."""
    fixed = {n for n, result in replay_results(run.line).items() if result is Replay.FIXED}
    return fixed <= numbers


def _moved_by_rule(run: Run, flags: frozenset[str]) -> bool:
    """Of a COUNTEREXAMPLE: findings with these flags alone cause it, so a rule not counting them
    would take it away. A finding without one, or any other cause, keeps it."""
    assert run.receipt is not None
    return not other_causes(run.receipt) and all(f.doubt in flags for f in run.receipt.findings)


def _doubt_rule(
    runs: Sequence[Run], flags: frozenset[str], labels: Mapping[Key, FindingLabel]
) -> Json:
    """What a rule not counting findings with these flags would do. On a correct fix a moved
    counterexample is a gain; on a wrong fix, a catch lost. A real bug's finding is dropped even
    if its run stays a counterexample through another finding."""

    def flagged(run: Run) -> set[int]:
        return {f.number for f in _found(run) if f.doubt in flags}

    def real_bug(run: Run, finding: FindingEntry) -> bool:
        found = label_for(run, labels, finding.number)
        return found is not None and found.label == "real_bug" and found.by == "developer"

    alarms = [r for r in runs if r.line.kind in CORRECT and _alarm(r, labels, "developer")]
    leftovers = [r for r in runs if r.line.kind in WRONG and _leftover_found(r)]
    real = [f for r in runs for f in _found(r) if real_bug(r, f)]
    return {
        "would_leave_counterexample": {
            kind: _rate_of(
                [r for r in runs if r.line.kind == kind and _level(r) == "COUNTEREXAMPLE"],
                lambda r: _moved_by_rule(r, flags),
            )
            for kind in _kinds(runs)
        },
        "false_alarms_gone": _rate_of(alarms, lambda r: _moved_by_rule(r, flags)),
        "real_bug_findings_dropped": rate(sum(f.doubt in flags for f in real), len(real)),
        "leftovers_lost": _rate_of(leftovers, lambda r: _found_only_through(r, flagged(r))),
    }


def doubt_counterfactual(runs: Sequence[Run], labels: Mapping[Key, FindingLabel]) -> Json:
    """The doubt flags (report only) per kind, and what a rule would do, for each flag and for
    all of them together: the developer decides per flag. No level reads this (M11 S5)."""

    def flags(read: Callable[[Run], Sequence[FindingEntry]]) -> Json:
        return {
            kind: _counts(f.doubt for r in runs if r.line.kind == kind
                          for f in read(r) if f.doubt is not None)
            for kind in _kinds(runs)
        }  # fmt: skip

    every = frozenset[str](get_args(Doubt))
    each = {flag: _doubt_rule(runs, frozenset({flag}), labels) for flag in get_args(Doubt)}
    return {
        "findings": flags(_found),
        "pre_existing": flags(_older),
        "rules": {"any": _doubt_rule(runs, every, labels), **each},
    }


def tricky_counterfactual(runs: Sequence[Run], labels: Mapping[Key, FindingLabel]) -> Json:
    """Findings whose input holds a tricky string (`uses_tricky_string`, M11 S6) per kind, the
    labels of those that need one, and the leftovers no other finding found. It reads the input
    each finding shows, so one with a plainer representative isn't counted."""

    def share(read: Callable[[Run], Sequence[FindingEntry]], kind: str) -> Json:
        found = [f for r in runs if r.line.kind == kind for f in read(r)]
        return rate(sum(uses_tricky_string(f.input) for f in found), len(found))

    def tricky(run: Run) -> set[int]:
        return {f.number for f in _found(run) if uses_tricky_string(f.input)}

    def verdict(run: Run, n: int) -> str:
        found = label_for(run, labels, n)
        return found.label if found and found.by == "developer" and found.label else "unreviewed"

    return {
        "findings": {kind: share(_found, kind) for kind in _kinds(runs)},
        "pre_existing": {kind: share(_older, kind) for kind in _kinds(runs)},
        "labels": {
            kind: _counts(
                verdict(r, n)
                for r in runs
                if r.line.kind == kind
                for n in tricky(r) & set(needs_label(r))
            )
            for kind in _kinds(runs)
        },
        "leftovers_only_through_them": _rate_of(
            [r for r in runs if r.line.kind in WRONG and _leftover_found(r)],
            lambda r: _found_only_through(r, tricky(r)),
        ),
    }


def _set_aside(runs: Sequence[Run], updated: Mapping[str, frozenset[str]]) -> set[Key]:
    """The runs that rest only on tests the PR updated (`rests_on_updated_tests`), each judged
    against its own arm's first gold run, as `summarise` does."""
    gold_first = {r.line.instance_id: r.receipt for r in runs
                  if r.line.kind == "gold" and r.line.repeat == 1}  # fmt: skip
    return {
        r.line.key
        for r in runs
        if rests_on_updated_tests(
            r, updated.get(r.line.instance_id, frozenset()), gold_first.get(r.line.instance_id)
        )
    }


def compare(
    a_runs: Sequence[Run], b_runs: Sequence[Run], prepared: Mapping[str, Prepared],
    a_labels: Mapping[Key, FindingLabel], b_labels: Mapping[Key, FindingLabel],
    updated: Mapping[str, frozenset[str]] | None = None,
) -> Json:  # fmt: skip
    """Arm B against arm A on the same units (task, kind, repeat). Wrong fixes: B finds the
    leftover where A doesn't (a win) or the reverse (a loss), and the one-sided sign test of
    B better; the same for not green-lighting them, per kind; and how far each kind's level
    moved. Correct fixes: each arm's developer-labelled false alarms. Each arm's misses, and
    what M11's plan measures on it. A run that timed out has no receipt and so no pair:
    `seconds_with_timeouts` adds an arm's own timeouts, at the seconds they ran, to its paired
    runs' times, which is what M11's time target reads (developer, 13 Nov 2026).

    As in the report, runs that rest only on tests the PR updated (`updated`: its test files by
    task) are left out of what is said about fixes: each arm's rates leave out its own, and a
    pair counts only if neither side is left out. The stage rows read every paired run."""
    pairs = paired(a_runs, b_runs)
    aside = (_set_aside(a_runs, updated or {}), _set_aside(b_runs, updated or {}))
    counted = [(a, b) for a, b in pairs
               if a.line.key not in aside[0] and b.line.key not in aside[1]]  # fmt: skip
    wrong = [(a, b) for a, b in counted if a.line.kind in WRONG]
    right = [(a, b) for a, b in counted if a.line.kind in CORRECT]
    keys = {a.line.key for a, _ in pairs}
    one, two = rank(EvidenceLevel.L1), rank(EvidenceLevel.L2)

    def not_green_lit(run: Run) -> bool:
        return _rank(run) <= one

    def unpaired(runs: Sequence[Run]) -> int:
        return sum(r.receipt is not None and r.line.key not in keys for r in runs)

    def arm(runs: Sequence[Run], index: int, labels: Mapping[Key, FindingLabel]) -> Json:
        all_runs = [pair[index] for pair in pairs]
        own = [r for r in all_runs if r.line.key not in aside[index]]
        wrong_runs = [r for r in own if r.line.kind in WRONG]
        right_runs = [r for r in own if r.line.kind in CORRECT]
        missed = misses(wrong_runs, prepared)
        seconds = [r.line.seconds for r in all_runs]
        timed_out = [r.line.seconds for r in runs if r.line.outcome == "timeout"]
        return {
            "leftover_found": _rate_of(wrong_runs, _leftover_found),
            "false_alarm": _rate_of(right_runs, lambda r: _alarm(r, labels, "developer")),
            "unreviewed": _rate_of(right_runs, lambda r: _unreviewed(r, labels)),
            "unpaired": unpaired(runs),
            "set_aside": len(all_runs) - len(own),
            "misses": missed,
            "reachable_misses": sum(n for cause, n in missed.items() if cause in REACHABLE),
            "headline": headline(own, labels),
            "gold_at_least_l2": _rate_of(
                [r for r in own if r.line.kind == "gold"], lambda r: _rank(r) >= two
            ),
            "guard_mutants": guard_mutants(all_runs),
            "no_input": _rate_of(all_runs, _no_input),
            "seconds": _stats(seconds),
            "timeouts": len(timed_out),
            "seconds_with_timeouts": _stats([*seconds, *timed_out]),
            "blind": blind_counterfactual(own),
            "doubt": doubt_counterfactual(own, labels),
            "tricky_strings": tricky_counterfactual(own, labels),
        }

    return {
        "pairs": {"wrong_fixes": len(wrong), "correct_fixes": len(right)},
        "wrong_fixes": _discordant(wrong, _leftover_found),
        "not_green_lit": {
            kind: _discordant([p for p in wrong if p[0].line.kind == kind], not_green_lit)
            for kind in WRONG
        },
        "levels": _level_moves(counted),
        "a": arm(a_runs, 0, a_labels),
        "b": arm(b_runs, 1, b_labels),
    }


def compare_by_split(
    cases: Sequence[Case], a_runs: Sequence[Run], b_runs: Sequence[Run],
    prepared: Mapping[str, Prepared], a_labels: Labels, b_labels: Labels,
) -> Json:  # fmt: skip
    """`compare` over all runs and for each split that has any."""
    split = {c.task.instance_id: c.split for c in cases}
    updated = {c.task.instance_id: updated_tests(c.task) for c in cases}
    a_by, b_by = (
        {label.key: label for label in labels.labels if label.label is not None}
        for labels in (a_labels, b_labels)
    )
    out = {"all": compare(a_runs, b_runs, prepared, a_by, b_by, updated)}
    for name in ("dev", "held_out"):
        a_of = [r for r in a_runs if split.get(r.line.instance_id) == name]
        b_of = [r for r in b_runs if split.get(r.line.instance_id) == name]
        if a_of or b_of:
            out[name] = compare(a_of, b_of, prepared, a_by, b_by, updated)
    return out


