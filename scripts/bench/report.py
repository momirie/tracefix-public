"""The benchmark's numbers (M10 plan P7, P8): pure functions from runs, receipts and labels.

Every number comes from a runs.jsonl line, a receipt our own code wrote, a prepare record or the
developer's label, never from a model's statement. Every rate carries its count (n of N). Only
the developer's labels count in the headline rates; labels Claude proposed are shown apart, and a
finding nobody labelled is never counted as a false alarm or as found.

`summarise` builds summary.json; `markdown` renders report.md from that summary alone, so the
report is regenerated byte for byte from the committed files.

Slice 2 adds agents' patches (M10 part 2 plan C5), only in a slice whose cases have agent runs:
`agent_wrong` (incorrect by our hidden runs: gate 3, read like the partial fix) and `agent_ok`
(correct by them: read like gold). Correct fixes, gold and agent_ok together, give gate 2's false
alarms. An agent_ok finding that gold passes "differs from gold" (likely a bug the hidden tests
miss) and is still labelled. Headline rates are also given by split and by the project's Python.

M11 compares two result sets only when asked (`compare`, its own files, so report.md never
changes): units both ran, paired by task, kind and repeat (`paired`); B's wins and losses on
wrong fixes with a one-sided exact sign test (`sign_test`); and why each wrong fix's leftover was
missed (`miss_cause`), from the receipt's Break My Fix targets and prepare's touched functions.
"""

