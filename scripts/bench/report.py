# --- labels -------------------------------------------------------------------------------------


RUN_ITSELF = 0  # a label's `finding` for a gold COUNTEREXAMPLE's causes no finding carries
FINDING_CAUSE = "Break My Fix finding "
Key = tuple[str, str, int]  # a label's (instance id, run tag, finding)


class FindingLabel(BaseModel):
    """One finding someone reviewed (or still has to: `label` None). Finding `RUN_ITSELF` is
    a gold fix's COUNTEREXAMPLE causes that no finding carries (the Reproducer's
    `fix_does_not_fix`, a regression), so every cause of a counterexample on gold can be judged,
    beside the findings' own labels. `receipt_created_at`
    names the very receipt judged: a run tried again keeps its tag but not its receipt, so a
    label written for the earlier attempt is stale and counts for nothing."""

    model_config = ConfigDict(frozen=True, extra="forbid", strict=True)

    instance_id: str
    run: str  # the run's tag, e.g. "gold-r1"
    finding: Annotated[int, Field(ge=RUN_ITSELF)]
    receipt_created_at: Annotated[str, StringConstraints(max_length=40)]
    label: Literal["real_bug", "false_alarm", "unclear"] | None = None
    by: Literal["developer", "claude-proposed"] | None = None
    note: Annotated[str, StringConstraints(max_length=2_000)] = ""

    @property
    def key(self) -> tuple[str, str, int]:
        return (self.instance_id, self.run, self.finding)


class Labels(BaseModel):
    """The labels file. Two entries for one finding are refused: which one counts would rest on
    their order in the file."""

    model_config = ConfigDict(frozen=True, extra="forbid", strict=True)

    labels: tuple[FindingLabel, ...] = ()

    @model_validator(mode="after")
    def _one_per_finding(self) -> Labels:
        seen = Counter(label.key for label in self.labels)
        twice = sorted(key for key, n in seen.items() if n > 1)
        if twice:
            raise ValueError(f"more than one label for {', '.join(map(str, twice[:5]))}")
        return self


@dataclass(frozen=True)
class Run:
    line: RunLine
    receipt: Receipt | None


def replay_results(line: RunLine) -> dict[int, Replay]:
    if line.replay is None:
        return {}
    return {f.number: f.result for f in line.replay.findings}


def other_causes(receipt: Receipt) -> list[str]:
    """A COUNTEREXAMPLE's causes that no finding carries: a regression, an integrity flag, a fix
    that doesn't fix the bug. Its level reasons are exactly its causes (`ladder.climb`), and a
    finding's reads "Break My Fix finding <n>: ..." (`ladder.counterexamples`)."""
    if receipt.level is not EvidenceLevel.COUNTEREXAMPLE:
        return []
    return [r for r in receipt.level_reasons if not r.startswith(FINDING_CAUSE)]


def _numbers(run: Run) -> list[int]:
    """The findings a label can point at: the receipt's, and `RUN_ITSELF` first for a correct
    fix's COUNTEREXAMPLE with no finding or with a cause no finding carries (an incorrect fix's
    COUNTEREXAMPLE is the detection we expect)."""
    if run.receipt is None:
        return []
    numbers = [f.number for f in run.receipt.findings]
    gold = run.line.kind in CORRECT and run.receipt.level is EvidenceLevel.COUNTEREXAMPLE
    itself = gold and (not numbers or bool(other_causes(run.receipt)))
    return [RUN_ITSELF, *numbers] if itself else numbers


def needs_label(run: Run) -> list[int]:
    """The findings a person has to judge: every one on a correct fix (it should have none),
    and an incorrect fix's that the gold fix doesn't pass (`fixed` on gold is our own
    confirmation)."""
    numbers = _numbers(run)
    if run.line.kind in CORRECT:
        return numbers
    fixed = {n for n, result in replay_results(run.line).items() if result is Replay.FIXED}
    return [n for n in numbers if n not in fixed]


def label_for(run: Run, labels: Mapping[Key, FindingLabel], n: int) -> FindingLabel | None:
    """Finding `n`'s label, if it was written for this very receipt (not a stale one)."""
    found = labels.get((run.line.instance_id, run.line.tag, n))
    if found is None or run.receipt is None:
        return None
    return found if found.receipt_created_at == run.receipt.created_at else None


def _stale_note(old: FindingLabel | None) -> str:
    if old is None:
        return ""
    verdict = "not labelled" if old.label is None else f"{old.label} by {old.by}"
    words = f"earlier attempt ({old.receipt_created_at}): {verdict}. {old.note}"
    return words.strip()[:2_000]


def with_missing(labels: Labels, runs: Iterable[Run]) -> Labels:
    """The labels, plus an empty entry for each finding that needs one and has none. A stale
    entry (written for an earlier attempt's receipt) is replaced in place by an empty one, its
    verdict kept in the note."""
    have = {label.key: label for label in labels.labels}
    fresh: dict[Key, FindingLabel] = {}
    for run in runs:
        if run.receipt is None:
            continue
        for n in needs_label(run):
            key = (run.line.instance_id, run.line.tag, n)
            old = have.get(key)
            if old is not None and old.receipt_created_at == run.receipt.created_at:
                continue
            fresh[key] = FindingLabel(
                instance_id=key[0], run=key[1], finding=n,
                receipt_created_at=run.receipt.created_at, note=_stale_note(old),
            )  # fmt: skip
    kept = [fresh.pop(label.key, label) for label in labels.labels]
    return Labels(labels=(*kept, *fresh.values()))


def orphaned(labels: Labels, runs: Iterable[Run]) -> list[str]:
    """The entries that count nowhere: their run has no receipt now, the receipt no such
    finding, or the entry names an earlier attempt's receipt and no finding needs it any more.
    Listed for a person to remove (`label` never deletes one)."""
    current = {(r.line.instance_id, r.line.tag): r for r in runs if r.receipt is not None}
    out = []
    for label in labels.labels:
        run = current.get((label.instance_id, label.run))
        mine = run is not None and label_for(run, {label.key: label}, label.finding) is not None
        if not (mine and run is not None and label.finding in _numbers(run)):
            out.append(f"{label.instance_id} {label.run} #{label.finding}")
    return out


# --- small helpers ------------------------------------------------------------------------------


def rate(n: int, of: int) -> Json:
    return {"n": n, "of": of}


def _rate_of(runs: Sequence[Run], test: Any) -> Json:
    return rate(sum(1 for r in runs if test(r)), len(runs))


def _counts(values: Iterable[str]) -> dict[str, int]:
    return dict(sorted(Counter(values).items()))


def _stats(values: Sequence[float]) -> Json:
    """Count, mean, median, 90th percentile (nearest rank: always one of the values) and max."""
    if not values:
        return {"n": 0}
    ordered = sorted(values)
    return {
        "n": len(values),
        "mean": round(statistics.fmean(values), 3),
        "median": round(statistics.median(values), 3),
        "p90": round(ordered[math.ceil(0.9 * len(ordered)) - 1], 3),
        "max": round(ordered[-1], 3),
    }


def stage(receipt: Receipt, name: str) -> StageEntry | None:
    return next((s for s in receipt.stages if s.name == name), None)


def reason_kind(text: str) -> str:
    """A reason with its run-specific parts (a leading function or file name, numbers) taken
    out, so the same reason from different runs counts as one."""
    text = re.sub(r"^[\w/.-]*[./_][\w/.-]*(?=[: ])", "<name>", text)
    return re.sub(r"\d+(\.\d+)?", "N", text)[:160]


def blocker(receipt: Receipt, rung: str) -> str | None:
    """The first reason the ladder gave for not reaching `rung` ("not L4: ..."), as a kind."""
    prefix = f"not {rung}: "
    found = next((r for r in receipt.level_reasons if r.startswith(prefix)), None)
    return None if found is None else reason_kind(found.removeprefix(prefix))


def _blockers(runs: Sequence[Run], at: str, rung: str) -> dict[str, int]:
    found = (blocker(r.receipt, rung) for r in runs if r.receipt and r.receipt.level.value == at)
    return _counts(b for b in found if b is not None)


def _level(run: Run) -> str:
    assert run.receipt is not None
    return run.receipt.level.value


def _rank(run: Run) -> int:
    assert run.receipt is not None
    return rank(run.receipt.level)


# --- the sections -------------------------------------------------------------------------------


def kinds_of(cases: Sequence[Case]) -> tuple[str, ...]:
    """The run kinds a slice has: gold and partial, and the agents' when its cases have them."""
    return ("gold", "partial", *(AGENT_KINDS if any(c.agents for c in cases) else ()))


def python_group(version: str) -> str | None:
    """The project's Python (prepare's probe) as one of PYTHONS; None when unknown."""
    major, _, rest = version.partition(".")
    minor = rest.partition(".")[0]
    if not (major.isdigit() and minor.isdigit()):
        return None
    return PYTHONS[1] if (int(major), int(minor)) >= (3, 11) else PYTHONS[0]


def funnel(cases: Sequence[Case], prepared: Mapping[str, Prepared], runs: Sequence[Run]) -> Json:
    records = [prepared[c.task.instance_id] for c in cases if c.task.instance_id in prepared]
    ready = [p for p in records if p.excluded is None]
    with_receipt = [r for r in runs if r.receipt is not None]
    kinds = kinds_of(cases)
    agents: Json = {}
    if len(kinds) > 2:  # each agent patch tried, by our label; one not kept is never run
        tried = (f"{a.kind}: {a.label.value}{'' if a.kept else ' (not run)'}"
                 for p in ready for a in p.agents)  # fmt: skip
        agents["agents"] = _counts(tried)
    return {
        "cases": len(cases),
        "prepared": len(records),
        "excluded": _counts(p.excluded.value for p in records if p.excluded is not None),
        "ready": len(ready),
        "ready_with_partial": sum(p.kept is not None for p in ready),
        **agents,
        "isolation_at_prepare": _counts(p.isolation or "unknown" for p in ready),
        "setup_commit_needed": sum(bool(p.setup_files or p.changed_files) for p in ready),
        "runs": {
            kind: _counts(r.line.outcome for r in runs if r.line.kind == kind) for kind in kinds
        },
        "receipt_status": _counts(r.receipt.status.value for r in with_receipt if r.receipt),
        "exit_codes": _counts(str(r.line.exit_code) for r in runs if r.line.exit_code is not None),
        "isolation": _counts(r.receipt.isolation.level for r in with_receipt if r.receipt),
        "stage_errors": _counts(
            s.name
            for r in with_receipt
            if r.receipt
            for s in r.receipt.stages
            if s.error is not None
        ),
    }


def _labelled(run: Run, labels: Mapping[tuple[str, str, int], FindingLabel]) -> list[FindingLabel]:
    found = (label_for(run, labels, n) for n in _numbers(run))
    return [label for label in found if label is not None]


def _has(
    run: Run, labels: Mapping[tuple[str, str, int], FindingLabel], value: str, by: str
) -> bool:
    return any(lb.label == value and lb.by == by for lb in _labelled(run, labels))


def _unreviewed(run: Run, labels: Mapping[tuple[str, str, int], FindingLabel]) -> bool:
    return any(
        (label := label_for(run, labels, n)) is None or label.by != "developer"
        for n in needs_label(run)
    )


def updated_tests(task: Task) -> frozenset[str]:
    """The files the PR's own test patch changes (Tracefix never sees that patch: plan P5).
    An unreadable test patch names none, so no run is set aside for it."""
    try:
        return files(task.test_patch) if task.test_patch else frozenset()
    except PatchError:
        return frozenset()


def _regressed(receipt: Receipt) -> set[tuple[str, str | None]]:
    return {(r.file, r.test) for r in receipt.regressions}


def rests_on_updated_tests(
    run: Run, updated: frozenset[str], gold_first: Receipt | None = None
) -> bool:
    """A COUNTEREXAMPLE whose every cause is a regression in a test file the PR's own test
    patch changed: the upstream PR updated that test with its fix, so the run says nothing about
    the fix and is set aside (developer, 17 Oct 2026). Any other fix's run is set aside only
    when gold's first run (`gold_first`) has every one of those regressions too: one gold
    doesn't share is the fix's own (NOTES #34 S4). A COUNTEREXAMPLE's level reasons are
    exactly its causes (`ladder.climb`), so any other cause keeps the run counted."""
    receipt = run.receipt
    if receipt is None or receipt.level is not EvidenceLevel.COUNTEREXAMPLE:
        return False
    only_regressions = all(r.startswith("regression: ") for r in receipt.level_reasons)
    in_updated = all(r.file in updated for r in receipt.regressions)
    if not (receipt.regressions and only_regressions and in_updated):
        return False
    if run.line.kind == "gold":
        return True
    return gold_first is not None and _regressed(receipt) <= _regressed(gold_first)


def set_aside(
    first: Sequence[Run], aside: Sequence[Run], kinds: Sequence[str] = ("gold", "partial")
) -> Json:
    """The first-repeat runs left out of the gold, partial, agent and separation sections."""

    def count(runs: Sequence[Run], kind: str) -> int:
        return sum(r.line.kind == kind for r in runs)

    return {
        **{kind: rate(count(aside, kind), count(first, kind)) for kind in kinds},
        "tasks": ", ".join(sorted({r.line.instance_id for r in aside})) or None,
    }


def _levels(runs: Sequence[Run]) -> Json:
    found = Counter(_level(r) for r in runs)
    return {level: found.get(level, 0) for level in LEVELS}


def _alarm(run: Run, labels: Mapping[Key, FindingLabel], by: str) -> bool:
    """A false alarm is a COUNTEREXAMPLE someone labelled one: a finding below that level
    raised no alarm (NOTES #34 N8)."""
    return _level(run) == "COUNTEREXAMPLE" and _has(run, labels, "false_alarm", by)


def is_false_alarm(run: Run, labels: Mapping[Key, FindingLabel]) -> bool:
    """Gate 2's false alarm: a COUNTEREXAMPLE the developer labelled one (scripts/site_data.py)."""
    return _alarm(run, labels, "developer")


def gold(runs: Sequence[Run], labels: Mapping[tuple[str, str, int], FindingLabel]) -> Json:
    """Correct fixes: a counterexample is a false alarm only by the developer's label."""
    two, three = rank(EvidenceLevel.L2), rank(EvidenceLevel.L3)
    return {
        "levels": _levels(runs),
        "counterexample": _rate_of(runs, lambda r: _level(r) == "COUNTEREXAMPLE"),
        "false_alarm": _rate_of(runs, lambda r: _alarm(r, labels, "developer")),
        "real_bug_in_gold": _rate_of(runs, lambda r: _has(r, labels, "real_bug", "developer")),
        "false_alarm_proposed": _rate_of(runs, lambda r: _alarm(r, labels, "claude-proposed")),
        "unreviewed": _rate_of(runs, lambda r: _unreviewed(r, labels)),
        "at_least_l2": _rate_of(runs, lambda r: _rank(r) >= two),
        "at_least_l3": _rate_of(runs, lambda r: _rank(r) >= three),
        "l4": _rate_of(runs, lambda r: _level(r) == "L4"),
    }


def _leftover_found(run: Run) -> bool:
    return any(result is Replay.FIXED for result in replay_results(run.line).values())


def agent_ok(runs: Sequence[Run], labels: Mapping[Key, FindingLabel]) -> Json:
    """Agents' patches the hidden tests pass: read as gold is, plus how often one of their
    findings passes on gold (the agent's fix differs from gold's there)."""
    return {**gold(runs, labels), DIFFERS: _rate_of(runs, _leftover_found)}


def headline(runs: Sequence[Run], labels: Mapping[Key, FindingLabel]) -> Json:
    """Gates 2 and 3 for one group of runs: false alarms on correct fixes (developer's labels),
    and incorrect fixes caught, not green-lit and with their leftover found."""
    one = rank(EvidenceLevel.L1)
    correct = [r for r in runs if r.line.kind in CORRECT]
    found: Json = {
        "correct_false_alarm": _rate_of(correct, lambda r: _alarm(r, labels, "developer")),
        "correct_unreviewed": _rate_of(correct, lambda r: _unreviewed(r, labels)),
        "agent_ok_false_alarm": _rate_of(
            [r for r in correct if r.line.kind == "agent_ok"],
            lambda r: _alarm(r, labels, "developer"),
        ),
    }
    for kind in ("partial", "agent_wrong"):
        of = [r for r in runs if r.line.kind == kind]
        found |= {
            f"{kind}_caught": _rate_of(of, lambda r: _level(r) == "COUNTEREXAMPLE"),
            f"{kind}_not_green_lit": _rate_of(of, lambda r: _rank(r) <= one),
            f"{kind}_leftover_found": _rate_of(of, _leftover_found),
        }
    return found


def by_group(
    runs: Sequence[Run], group: Callable[[Run], str | None], groups: Sequence[str],
    labels: Mapping[Key, FindingLabel],
) -> Json:  # fmt: skip
    return {g: headline([r for r in runs if group(r) == g], labels) for g in groups}


def partial(runs: Sequence[Run], labels: Mapping[tuple[str, str, int], FindingLabel]) -> Json:
    """Incomplete fixes: the hidden tests showed each one incomplete."""
    one, two, three = rank(EvidenceLevel.L1), rank(EvidenceLevel.L2), rank(EvidenceLevel.L3)
    return {
        "levels": _levels(runs),
        "detection": _rate_of(runs, lambda r: _level(r) == "COUNTEREXAMPLE"),
        "not_green_lit": _rate_of(runs, lambda r: _rank(r) <= one),
        "false_pass_l2": _rate_of(runs, lambda r: _rank(r) >= two),
        "false_pass_l3": _rate_of(runs, lambda r: _rank(r) >= three),
        "leftover_found": _rate_of(runs, _leftover_found),
        "real_bug_by_label": _rate_of(runs, lambda r: _has(r, labels, "real_bug", "developer")),
        "unreviewed": _rate_of(runs, lambda r: _unreviewed(r, labels)),
    }


def separation(gold_runs: Sequence[Run], partial_runs: Sequence[Run]) -> Json:
    by_task = {r.line.instance_id: r for r in gold_runs}
    pairs = [
        (by_task[p.line.instance_id], p) for p in partial_runs if p.line.instance_id in by_task
    ]
    return {
        "gold_above": rate(sum(_rank(g) > _rank(p) for g, p in pairs), len(pairs)),
        "same": rate(sum(_rank(g) == _rank(p) for g, p in pairs), len(pairs)),
        "gold_below": rate(sum(_rank(g) < _rank(p) for g, p in pairs), len(pairs)),
    }


def _status(run: Run, name: str) -> str:
    assert run.receipt is not None
    entry = stage(run.receipt, name)
    return "absent" if entry is None else entry.status


def reproducer(gold_runs: Sequence[Run]) -> Json:
    return {
        "statuses": _counts(_status(r, "reproduce") for r in gold_runs),
        "fail_to_pass": _rate_of(gold_runs, lambda r: _status(r, "reproduce") == "reproduced"),
        "fix_does_not_fix": _rate_of(
            gold_runs, lambda r: _status(r, "reproduce") == "fix_does_not_fix"
        ),
    }


def _evidence(run: Run, name: str) -> Mapping[str, object]:
    assert run.receipt is not None
    entry = stage(run.receipt, name)
    return {} if entry is None else entry.evidence


def _int(value: object) -> int:
    return value if isinstance(value, int) and not isinstance(value, bool) else 0


def guard(runs: Sequence[Run]) -> Json:
    rates = [v for r in runs if isinstance(v := _evidence(r, "guard").get("kill_rate"), float)]
    killed = sum(_int(_evidence(r, "guard").get("killed")) for r in runs)
    crash = sum(_int(_evidence(r, "guard").get("crash_kills")) for r in runs)
    return {
        "statuses": _counts(_status(r, "guard") for r in runs),
        "guarded": _rate_of(runs, lambda r: _status(r, "guard") == "guarded"),
        "kill_rate": _stats(rates),
        "crash_only_kills": rate(crash, killed),
    }


def _reason(run: Run, name: str) -> str:
    assert run.receipt is not None
    entry = stage(run.receipt, name)
    return "" if entry is None else reason_kind(entry.reason)


def break_my_fix(runs: Sequence[Run]) -> Json:
    name = "break_my_fix"
    targets = sum(_int(_evidence(r, name).get("targets")) for r in runs)
    inputs = sum(_int(_evidence(r, name).get("inputs_tried")) for r in runs)
    not_attacked = [r for r in runs if _status(r, name) in ("skipped", "inconclusive")]
    return {
        "statuses": _counts(_status(r, name) for r in runs),
        "skip_reasons": _counts(_reason(r, name) for r in not_attacked),
        "targets": targets,
        "inputs_per_target": round(inputs / targets, 1) if targets else None,
        "pre_existing": sum(len(r.receipt.pre_existing) for r in runs if r.receipt),
        "first_l4_blocker": _blockers(runs, "L3", "L4"),
    }


def behaviour_diff(runs: Sequence[Run]) -> Json:
    name = "behaviour_diff"
    gated = [r for r in runs if "l3_gate" in _evidence(r, name)]
    closed = [r for r in gated if _evidence(r, name).get("l3_gate") is not True]
    return {
        "statuses": _counts(_status(r, name) for r in runs),
        "l3_gate_open": rate(len(gated) - len(closed), len(gated)),
        "first_l3_blocker": _blockers(runs, "L2", "L3"),
    }


def report_only(runs: Sequence[Run]) -> Json:
    """Signals that never set a level: fix-line coverage and the no-regression check."""
    ran: Counter[str] = Counter()
    total: Counter[str] = Counter()
    for r in runs:
        coverage = r.receipt.fix_line_coverage if r.receipt else None
        for s in coverage.sets if coverage else ():
            ran[s.name] += s.ran
            total[s.name] += s.total
    return {
        "fix_line_coverage": {name: rate(ran[name], total[name]) for name in sorted(total)},
        "regressions": _counts(_status(r, "regressions") for r in runs),
    }


def cost_and_time(runs: Sequence[Run], all_lines: Sequence[RunLine], reserve: float) -> Json:
    with_receipt = [r for r in runs if r.receipt is not None]
    costs = [r.receipt.llm.cost_estimate.usd for r in with_receipt if r.receipt]
    known = [c for c in costs if c is not None]
    durations: dict[str, list[float]] = {}
    for r in with_receipt:
        for s in r.receipt.stages if r.receipt else ():
            durations.setdefault(s.name, []).append(s.duration_s)
    live = attempts(all_lines)
    return {
        "usd_per_run": _stats(known),
        "usd_unknown": len(costs) - len(known),
        # what the spend guard counts: every live attempt, one of unknown cost as a whole reserve
        "usd_spent_live": round(spent(all_lines, reserve), 2),
        "usd_spent_known": round(sum(line.spend_usd or 0.0 for line in live), 2),
        "live_attempts_cost_unknown": sum(line.spend_usd is None for line in live),
        "calls": _stats([float(r.receipt.llm.calls) for r in with_receipt if r.receipt]),
        "tokens": _stats(
            [
                float(r.receipt.llm.input_tokens + r.receipt.llm.output_tokens)
                for r in with_receipt
                if r.receipt
            ]
        ),
        "seconds_per_run": _stats([r.line.seconds for r in runs]),
        "seconds_per_stage": {name: _stats(v) for name, v in sorted(durations.items())},
    }


def stability(runs: Sequence[Run]) -> Json:
    """Repeated runs of the same task and kind: how often the level, the COUNTEREXAMPLE verdict
    (what the gold and partial rates rest on), Guard's status or having a finding differ."""
    groups: dict[tuple[str, str], list[Run]] = {}
    for r in runs:
        if r.receipt is not None:
            groups.setdefault((r.line.instance_id, r.line.kind), []).append(r)
    repeated = [g for g in groups.values() if len(g) >= 2]

    def flips(value: Callable[[Run], object]) -> Json:
        return rate(sum(len({value(r) for r in g}) > 1 for g in repeated), len(repeated))

    return {
        "groups": len(repeated),
        "level_flips": flips(_level),
        "counterexample_flips": flips(lambda r: _level(r) == EvidenceLevel.COUNTEREXAMPLE.value),
        "guard_flips": flips(lambda r: _status(r, "guard")),
        "finding_flips": flips(lambda r: bool(r.receipt and r.receipt.findings)),
    }


