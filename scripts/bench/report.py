def show(value: object) -> str:
    """A rate as "n/N (p%)"; anything else as itself."""
    if isinstance(value, dict) and set(value) == {"n", "of"}:
        n, of = value["n"], value["of"]
        return f"{n}/{of} ({100 * n / of:.0f}%)" if of else f"{n}/0"
    if isinstance(value, dict) and "mean" in value:
        return (
            f"mean {value['mean']}, median {value['median']}, p90 {value['p90']}, "
            f"max {value['max']} (n={value['n']})"
        )
    if isinstance(value, dict) and value == {"n": 0}:
        return "none"
    if isinstance(value, dict):
        return ", ".join(f"{k}: {show(v)}" for k, v in value.items()) or "none"
    return "none" if value is None else str(value)


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _table(rows: Mapping[str, object]) -> list[str]:
    lines = ["| | |", "|---|---|"]
    lines += [f"| {_cell(k)} | {_cell(show(v))} |" for k, v in rows.items()]
    return [*lines, ""]


def markdown(summary: Json, title: str) -> str:
    out = [f"# {title}", "",
           "Every number comes from a run, a receipt, a prepare record or the developer's label",
           "(scripts/bench/report.py). Rates show n/N. Headline sections read each task's first",
           "repeat. Set aside: COUNTEREXAMPLEs whose only causes are regressions in test files",
           "the PR's own test patch changed; the gold, partial and separation sections leave",
           "them out.", ""]  # fmt: skip
    if "agent_wrong" in summary:
        out += ["Agent fixes: OpenHands patches our own hidden-test runs show wrong",
                    "(agent_wrong) or right (agent_ok). Correct fixes are gold and agent_ok;",
                    f"{DIFFERS}: an agent_ok finding that passes on gold.", ""]  # fmt: skip
    for section, body in summary.items():
        if section == "findings":
            continue
        out.append(f"## {section.replace('_', ' ').capitalize()}")
        out.append("")
        if isinstance(body, dict) and body and all(isinstance(v, dict) for v in body.values()) \
                and set(body) <= SUBSECTIONS:  # fmt: skip
            for kind, part in body.items():
                out += [f"### {kind}", "", *_table(part)]
        else:
            out += _table(body)
    out += ["## Findings", ""]
    rows = summary.get("findings", [])
    if not rows:
        return "\n".join([*out, "none", ""])
    out += [
        "| task | run | # | call | outcome | replay on gold | label |",
        "|---|---|---|---|---|---|---|",
    ]
    for f in rows:
        label = f"{f['label']} ({f['by']})" if f["label"] else "unreviewed"
        number = "-" if f["finding"] == RUN_ITSELF else str(f["finding"])
        cells = [f["instance_id"], f["run"], number, f["call"], f["outcome"],
                 f["replay_on_gold"] or "-", label]  # fmt: skip
        out.append("| " + " | ".join(_cell(c) for c in cells) + " |")
    return "\n".join([*out, ""])
