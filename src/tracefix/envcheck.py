"""Where the changed code is imported from (SPEC 2.1, Decided in M8; NOTES 6).

Runs put the copy's package folders ahead of installed packages (sandbox.PATHS_SOURCE), but an
import hook, a conftest or a plugin can still send an import elsewhere, e.g. to an editable
install of the user's working copy. Then every stage would test that code instead of the commit
under test. So after the environment check, one watched run per copy imports every changed
source module by its name under the import roots and reports the file it came from; one that
comes from outside the copy stops the run with ENVIRONMENT_ERROR. A module that doesn't import
at all is left to the stages, which report it in their own words. A changed source file that
has no import name (outside every import root, e.g. in a namespace package) can't be checked:
the receipt lists it as not checked. Scripts such as setup.py are never imported (that runs them).

The report is written inside the process under test, so it is untrusted: hostile code could lie
in it. The check catches a misconfigured environment; hostile code is the tamper watch's job.
"""

import json
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path, PurePosixPath

from tracefix.diffscope import DiffScope
from tracefix.harness import placed, run_file
from tracefix.runner import EnvStatus, Probe, RunResult
from tracefix.workspace import Workspace, is_script_or_test

ORIGIN_TEST = "test_tracefix_imports.py"
MAX_MODULES = 200
ORIGIN_CODE = '''\
"""Tracefix's import origin check, generated by Tracefix and removed after the run."""

import importlib
import json
import os

MODULES = {modules!r}


def test_tracefix_imports():
    with open(os.environ["TRACEFIX_OUT"], "a", encoding="utf-8") as out:
        for name in MODULES:
            try:
                module = importlib.import_module(name)
            except BaseException as exc:
                found = {{"module": name, "error": type(exc).__name__}}
            else:
                found = {{"module": name, "file": getattr(module, "__file__", None)}}
            out.write(json.dumps(found, default=str) + "\\n")
'''


@dataclass(frozen=True)
class Origin:
    """One changed module, imported in one copy."""

    side: str  # "base" or "head"
    module: str  # e.g. "pager.pagination"
    file: str | None  # where it was imported from, as the run reported it
    error: str | None  # the exception type, when it didn't import (left to the stages)
    inside: bool  # the file is inside the copy under test


@dataclass(frozen=True)
class OriginCheck:
    status: EnvStatus
    reason: str
    origins: tuple[Origin, ...]
    runs: tuple[tuple[str, RunResult], ...]  # (label, run), for the receipt's commands
    unchecked: tuple[str, ...] = ()  # changed source files with no import name (not checked)


def module_name(path: str, roots: Sequence[str]) -> str | None:
    """The import name of a source file under the deepest import root that holds it, or None
    (not under a root, not a .py file, a __main__, or a part that isn't an identifier)."""
    pure = PurePosixPath(path)
    if pure.suffix != ".py" or pure.stem == "__main__":
        return None
    for root in sorted(roots, key=lambda r: -len(PurePosixPath(r).parts)):
        if root != "." and not pure.is_relative_to(root):
            continue
        rel = pure if root == "." else pure.relative_to(root)
        parts = [*rel.parent.parts, rel.stem] if rel.stem != "__init__" else [*rel.parent.parts]
        if parts and all(part.isidentifier() for part in parts):
            return ".".join(parts)
        return None
    return None


def _changed_sources(scope: DiffScope) -> set[str]:
    """Changed source files that may be the project's code (no scripts such as setup.py)."""
    paths = {p for f in scope.source_files for p in (f.old_path, f.path) if p}
    return {p for p in paths if not is_script_or_test(PurePosixPath(p).name)}


def changed_modules(ws: Workspace, scope: DiffScope, copy: Path) -> list[str]:
    """Import names of the changed source files present in a copy, sorted, at most MAX_MODULES."""
    paths = _changed_sources(scope)
    names = {module_name(p, ws.import_roots) for p in paths if p in ws.pristine[copy]}
    return sorted(n for n in names if n is not None)[:MAX_MODULES]


def nameless(ws: Workspace, scope: DiffScope) -> tuple[str, ...]:
    """Changed .py source files in either copy that have no import name: not checked."""
    present = set(ws.pristine[ws.base]) | set(ws.pristine[ws.head])
    return tuple(sorted(p for p in _changed_sources(scope) if p in present and p.endswith(".py")
                        and module_name(p, ws.import_roots) is None))  # fmt: skip


def _inside(file: str, copy: Path) -> bool:
    try:
        return Path(file).resolve().is_relative_to(copy.resolve())
    except (OSError, ValueError, RuntimeError):
        return False


def _origins(side: str, out: str | None, modules: Sequence[str], copy: Path) -> list[Origin]:
    """The run's report, read defensively: only well-formed lines about the modules asked for."""
    found: dict[str, Origin] = {}
    for line in (out or "").splitlines():
        try:
            entry = json.loads(line)
        except ValueError:
            continue
        if not isinstance(entry, dict) or entry.get("module") not in modules:
            continue
        name = entry["module"]
        file, error = entry.get("file"), entry.get("error")
        if isinstance(file, str):
            found[name] = Origin(side, name, file, None, _inside(file, copy))
        elif isinstance(error, str):
            found[name] = Origin(side, name, None, error[:100], True)
    return [found[m] for m in modules if m in found]


def _reason(outside: Sequence[Origin]) -> str:
    first = outside[0]
    more = f" (and {len(outside) - 1} more)" if len(outside) > 1 else ""
    return (
        f"in the {first.side} copy, the changed module {first.module!r} is imported from "
        f"{first.file}, outside the copy{more}: an installed copy of the project (for example an "
        "editable install) or an import hook wins over the code under test, so the tests would "
        "not test this change"
    )


def origin_check(ws: Workspace, scope: DiffScope) -> OriginCheck:
    """Import the changed modules in the base and head copies and check where they came from.
    Raises TamperingDetected like any watched run."""
    origins: list[Origin] = []
    runs: list[tuple[str, RunResult]] = []
    for side, copy in (("base", ws.base), ("head", ws.head)):
        modules = changed_modules(ws, scope, copy)
        if not modules:
            continue
        code = ORIGIN_CODE.format(modules=modules)
        run = run_file(ws, copy, placed(ws, ORIGIN_TEST), code, ws.settings.suite_timeout_s, 0,
                       Probe())  # fmt: skip
        runs.append((f"the import origin check in the {side} copy", run))
        origins += _origins(side, run.first.out, modules, copy)
    unchecked = nameless(ws, scope)
    outside = [o for o in origins if not o.inside]
    if outside:
        return OriginCheck(EnvStatus.ENVIRONMENT_ERROR, _reason(outside), tuple(origins),
                           tuple(runs), unchecked)  # fmt: skip
    checked = [o for o in origins if o.error is None]
    distinct = len({o.module for o in checked})
    reason = (
        f"{distinct} changed module(s) imported from the copies ({len(checked)} imports in all)"
        if runs
        else "no changed module under the package folders to check"
    )
    if unchecked:
        reason += f"; {len(unchecked)} changed source file(s) have no import name, not checked"
    return OriginCheck(EnvStatus.OK, reason, tuple(origins), tuple(runs), unchecked)
