"""Running Tracefix's in-run code (attack_runtime) and other generated test files in a copy.

Shared by Break My Fix and the behaviour diff. A generated test file is written next to the
repo's tests (so their conftest and config apply), run watched through `isolation.run_checked`,
and removed again. The runtime goes into the run's scratch folder under a random module name, so
a repo can't plant a module of that name; what it reports comes back through `TRACEFIX_OUT` and is
untrusted data.
"""

import json
import secrets
from collections.abc import Mapping, Sequence
from pathlib import Path, PurePosixPath
from typing import Any

from tracefix import attack_runtime, runtime_state
from tracefix.attack_rules import read_events
from tracefix.isolation import run_checked
from tracefix.repro import repro_test_path
from tracefix.runner import Probe, RunResult
from tracefix.workspace import Workspace, WorkspaceError

HARNESS = '''\
"""Tracefix {mode} run, generated by Tracefix and removed after the run."""

import {module} as runtime

PLAN = {plan!r}


def test_tracefix_{mode}():
    runtime.main(PLAN)
'''
_RUNTIME = Path(attack_runtime.__file__).read_text(encoding="utf-8")
_STATE = Path(runtime_state.__file__).read_text(encoding="utf-8")
_STATE_IMPORT = "from tracefix.runtime_state import ("
if _RUNTIME.count(_STATE_IMPORT) != 1:  # the one line runtime_modules points elsewhere
    raise RuntimeError("attack_runtime must import runtime_state in exactly one statement")


def runtime_modules(module: str) -> dict[str, str]:
    """Tracefix's in-run code for one run, by module name: attack_runtime as `module`, and the
    state readers it imports (runtime_state) beside it as `<module>_state`. Both names are random
    per run, so a repo can't plant either; the runtime's one import of the state readers is
    pointed at that name. Nothing in them imports tracefix."""
    runtime = _RUNTIME.replace(_STATE_IMPORT, f"from {module}_state import (")
    return {module: runtime, f"{module}_state": _STATE}


def placed(ws: Workspace, name: str) -> str:
    """Where a generated test file goes: next to the repo's tests (so their conftest and config
    apply), like the reproduction test."""
    folder = PurePosixPath(repro_test_path(ws, None)).parent
    return name if str(folder) == "." else str(folder / name)


def run_file(
    ws: Workspace,
    tree: Path,
    rel: str,
    code: str,
    timeout: float,
    reruns: int,
    probe: Probe | None = None,
    swapped_in: Sequence[str] = (),
    pytest_args: Sequence[str] = (),
) -> RunResult:
    """Write a generated test file into a copy, run it watched, and remove it again.
    `swapped_in`: other files Tracefix itself put into the copy for this run (a mutant)."""
    target = tree / rel
    if target.exists():
        raise WorkspaceError(f"{rel} already exists in the repo, so it is not overwritten")
    target.write_text(code, encoding="utf-8", newline="\n")
    try:
        return run_checked(
            ws,
            tree,
            [rel],
            placed=[rel, *swapped_in],
            timeout_s=timeout,
            reruns=reruns,
            probe=probe,
            pytest_args=pytest_args,
        )
    finally:
        target.unlink(missing_ok=True)


def run_harness(
    ws: Workspace,
    tree: Path,
    mode: str,
    plan: Mapping[str, Any],
    timeout: float,
    swapped_in: Sequence[str] = (),
) -> tuple[list[dict[str, Any]], int, RunResult]:
    """Run attack_runtime with a plan inside a watched run: its events, how many lines of its
    report were unreadable, and the run. `swapped_in`: files Tracefix put into the copy."""
    module = f"tracefix_rt_{secrets.token_hex(4)}"  # a repo can't plant a module of this name
    code = HARNESS.format(mode=mode, module=module, plan=json.dumps(plan, sort_keys=True))
    rel = placed(ws, f"test_tracefix_{mode}.py")
    probe = Probe(runtime_modules(module))
    # A diff run reads file descriptors itself; with pytest's capture off (-s), a stream a
    # module kept from import time is the real one (verifier round 7, B8).
    extra = ("-s",) if mode == "diff" else ()
    run = run_file(ws, tree, rel, code, timeout, 0, probe, swapped_in, extra)
    events, bad = read_events(run.first.out)
    return events, bad, run
